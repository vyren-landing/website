export function localeLabel(value: string, turkish: boolean): string {
  if (!turkish) return value;
  if (TR_LABELS[value]) return TR_LABELS[value];
  const actions: [RegExp,string][] = [
    [/^New simulated person: (.*)$/, "Yeni test kişisi: $1"],
    [/^Position created: (.*)$/, "Pozisyon oluşturuldu: $1"],
    [/^Demo task created: (.*)$/, "Test görevi oluşturuldu: $1"],
    [/^Demo opportunity created: (.*)$/, "Test fırsatı oluşturuldu: $1"],
    [/^(.*) moved to (.*)$/, "$1 durumu: $2"],
    [/^(.*) changed stage$/, "$1 aşaması değiştirildi"]
  ];
  for (const [regex, replacement] of actions) { if(regex.test(value)) return value.replace(regex,replacement); }
  return value;
}
